"""Generate docs/MEASUREMENTS.md from the .scad parameters and the built STLs.

Usage: python tools/param_table.py
Run by build.ps1 after the STLs are exported. Standard library only.

The .scad files stay the single source of truth: this script only reads them.
It picks up every top-level `name = value; // comment` line above the
"// ---- derived ----" marker, grouped by the `/* [Section] */` headers, and
follows `include <...>` so shared values (ring_common.scad) appear too.
"""
import os
import re
import sys

from check_stl import measure

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "MEASUREMENTS.md")

# (title, scad file, [(label, stl), ...])
MODELS = [
    ("Solid block (primary)", "ring_mount.scad",
     [("Block", "stl/ring_mount.stl")]),
    ("Adjustable mount (option 2)", "ring_mount_adjustable.scad",
     [("Base", "stl/adjustable_base.stl"),
      ("Shell", "stl/adjustable_shell.stl"),
      ("Washer", "stl/adjustable_washer.stl"),
      ("Fit test (3 pieces, as laid out)", "stl/adjustable_fit_test.stl")]),
]
SKIP_SECTIONS = {"Render", "Quality"}

SECTION = re.compile(r"/\*\s*\[([^\]]+)\]\s*(.*?)\*/")
INCLUDE = re.compile(r"^\s*include\s*<([^>]+)>")
PARAM = re.compile(r"^([A-Za-z_]\w*)\s*=\s*([^;]+);\s*(?://\s*(.*))?$")
TAG = re.compile(r"^\[(written\??|scaled|chosen)\]\s*(.*)$")


def parse(path, section="General"):
    """Yield (section, name, value, source, note) for each parameter."""
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("// ---- derived"):
                return
            if re.match(r"^\s*(module|function)\b", line):
                return
            m = INCLUDE.match(line)
            if m:
                yield from parse(os.path.join(os.path.dirname(path), m.group(1)), section)
                continue
            m = SECTION.search(line)
            if m:
                section = m.group(1).strip()
                continue
            m = PARAM.match(line.strip())
            if not m or section in SKIP_SECTIONS:
                continue
            name, value, comment = m.group(1), m.group(2).strip(), (m.group(3) or "").strip()
            t = TAG.match(comment)
            source, note = (t.group(1), t.group(2)) if t else ("tolerance" if section == "Print tolerances" else "", comment)
            yield section, name, value, source, note


def cell(text):
    return text.replace("|", "\\|")


def model_section(title, scad, stls):
    lines = [f"## {title}", "", f"Source file: [`{scad}`](../{scad})", ""]

    lines += ["### Built size (from the exported STLs)", "",
              "| Part | X × Y × Z (mm) | Volume (cm³) | Watertight |", "|---|---|---|---|"]
    for label, stl in stls:
        path = os.path.join(ROOT, stl)
        if not os.path.exists(path):
            lines.append(f"| {label} | not built | | |")
            continue
        _, _, size, volume, bad = measure(path)
        dims = " × ".join(f"{s:.2f}" for s in size)
        lines.append(f"| [{label}](../{stl}) | {dims} | {volume / 1000:.2f} | {'yes' if bad == 0 else 'NO'} |")
    lines.append("")

    current = None
    for section, name, value, source, note in parse(os.path.join(ROOT, scad)):
        if section != current:
            current = section
            lines += [f"### {section}", "", "| Parameter | Value | Source | Notes |", "|---|---|---|---|"]
        lines.append(f"| `{name}` | {cell(value)} | {source} | {cell(note)} |")
        # blank line after each table happens when the section changes
    lines.append("")
    # insert blank lines between consecutive tables
    out = []
    for i, ln in enumerate(lines):
        if ln.startswith("### ") and out and out[-1] != "":
            out.append("")
        out.append(ln)
    return out


def main():
    lines = [
        "# Measurements",
        "",
        "<!-- GENERATED by tools/param_table.py during build.ps1. Do not edit by hand:",
        "     change the value in the .scad file and rebuild. -->",
        "",
        "Generated from the model files on every build, so it always matches what",
        "was printed. **To change a value, edit it in the `.scad` file and run",
        "`build.ps1`**; never edit this file.",
        "",
        "Lengths in mm, angles in degrees. Source key: **written** = on the hand",
        "sketch (`written?` = hard to read) · **scaled** = measured off the sketch,",
        "about ±1 mm · **chosen** = design decision · **tolerance** = print",
        "clearance, tune with the fit test.",
        "",
        "Axes: X = width (0 = deep side, against the mounting surface) · Y = depth",
        "(0 = back face, cable entry) · Z = height (0 = bottom).",
        "",
    ]
    for title, scad, stls in MODELS:
        lines += model_section(title, scad, stls)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines).rstrip() + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    sys.exit(main())
